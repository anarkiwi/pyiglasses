GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
ADVANCE = GLYPH_WIDTH + 1


def render(text):
    """Return a boolean (7, 6 * len(text)) mask of ``text``."""
    text = text.upper()
    mask = np.zeros((GLYPH_HEIGHT, ADVANCE * len(text)), bool)
    for index, char in enumerate(text):
        try:
            columns = GLYPHS[char]
        except KeyError:
            raise ValueError(f"no glyph for {char!r}") from None
        bits = np.array(columns, np.uint8)[:, None] >> np.arange(GLYPH_HEIGHT)
        mask[:, index * ADVANCE : index * ADVANCE + GLYPH_WIDTH] = (bits & 1).T.astype(
            bool
        )
    return mask


def draw(image, text, x, y, scale=1, colour=(255, 255, 255)):
    """Draw ``text`` into an RGB image with its top left corner at (x, y)."""
    mask = np.repeat(np.repeat(render(text), scale, axis=0), scale, axis=1)
    height, width = mask.shape
    height = min(height, image.shape[0] - y)
    width = min(width, image.shape[1] - x)
    if height <= 0 or width <= 0:
        return image
    window = image[y : y + height, x : x + width]
    window[mask[:height, :width]] = colour
    return image


def text_size(text, scale=1):
    """Return the (height, width) of rendered text."""
    return GLYPH_HEIGHT * scale, ADVANCE * len(text) * scale
